#!/usr/bin/env python3
r"""Generate paper/numbers.tex from paper/registry/*.yaml.

Every number quoted in the paper text comes from a JSON file under data/derived/.

Formats: `fmt` is a Python format string ("{:.2f}"), or "sci" for scientific notation, or "p" for a p-value (with a companion <name>Rel macro carrying "=" or "<") in LaTeX,
e.g. 0.000234 -> \ensuremath{2.3\times10^{-4}}. With "sci" the optional `digits` (default 2) is
the number of significant digits of the mantissa; an exponent of 0 prints the mantissa alone.
"sig" prints `digits` (default 2) significant figures in fixed notation, rounded half up; "floor" the same
rounded down, for lower bounds.
Fails with a non-zero exit status and a message naming the macro if a file or
key is missing, a format string does not fit the value, or a name is invalid.
"""
import argparse
import json
import re
import sys
from pathlib import Path

import math
from decimal import Decimal, ROUND_HALF_UP
import yaml

ROOT = Path(__file__).resolve().parent.parent


def lookup(obj, path):
    """Walk a dotted key path; integer components index into lists."""
    for part in path.split("."):
        if isinstance(obj, list):
            try:
                obj = obj[int(part)]
            except (ValueError, IndexError):
                raise KeyError(path)
        elif isinstance(obj, dict) and part in obj:
            obj = obj[part]
        else:
            raise KeyError(path)
    return obj


def sci(val, digits=2):
    """LaTeX scientific notation with `digits` significant digits in the mantissa."""
    if isinstance(val, bool) or not isinstance(val, (int, float)):
        raise TypeError(f"sci needs a number, got {type(val).__name__}")
    if not isinstance(digits, int) or digits < 1:
        raise ValueError("digits must be a positive integer")
    if val == 0:
        return "\\ensuremath{0}"
    mant, exp = f"{val:.{digits - 1}e}".split("e")
    exp = int(exp)
    body = mant if exp == 0 else f"{mant}\\times10^{{{exp}}}"
    return f"\\ensuremath{{{body}}}"


def sigfmt(val, digits=2, floor=False):
    """`digits` significant figures in fixed notation; floor=True rounds down (for lower bounds)."""
    if val == 0:
        return "0"
    e = math.floor(math.log10(abs(val)))
    q = 10.0 ** (e - digits + 1)
    r = (math.floor(val / q) if floor else math.floor(val / q + 0.5)) * q
    dec = max(digits - 1 - e, 0)
    return f"{r:.{dec}f}"


def pfmt(val, digits=2):
    """p-values: `digits` significant figures down to 1e-3, "<10^{-k}" below (k = floor(-log10 p))."""
    if isinstance(val, bool) or not isinstance(val, (int, float)):
        raise TypeError(f"p needs a number, got {type(val).__name__}")
    if not 0 <= val <= 1:
        raise ValueError(f"p-value out of [0, 1]: {val}")
    if val >= 1e-3:
        dec = max(digits - 1 - math.floor(math.log10(val)), 0)
        q = Decimal(repr(val)).quantize(Decimal(1).scaleb(-dec), rounding=ROUND_HALF_UP)
        dec = max(digits - 1 - math.floor(math.log10(float(q))), 0)  # rounding may carry to the next decade
        q = q.quantize(Decimal(1).scaleb(-dec), rounding=ROUND_HALF_UP)
        return f"{q:.{dec}f}"
    k = math.floor(-math.log10(val)) if val > 0 else 16
    return f"\\ensuremath{{<10^{{-{k}}}}}"


def prel(val, digits=2):
    """The relation and value for running text: "=0.012" or "<10^{-3}"."""
    text = pfmt(val, digits)
    return text if "<" in text else f"\\ensuremath{{={text}}}"


def load_registry(path):
    """Load one registry file, or every *.yaml in a directory (sorted); duplicate macros fail."""
    path = Path(path)
    files = sorted(path.glob("*.yaml")) if path.is_dir() else [path]
    reg, origin = {}, {}
    for f in files:
        part = yaml.safe_load(f.read_text()) or {}
        if not isinstance(part, dict):
            raise SystemExit(f"{f}: top level must be a mapping")
        for name, spec in part.items():
            if name in reg:
                raise SystemExit(f"make_numbers: duplicate macro '{name}' in {origin[name].name} and {f.name}")
            reg[name], origin[name] = spec, f
    return reg


def build(registry_path, derived_dir):
    reg = load_registry(registry_path)
    lines = ["% generated by tools/make_numbers.py from paper/registry/*.yaml; do not edit"]
    cache = {}
    for name, spec in reg.items():
        def fail(msg):
            raise SystemExit(f"make_numbers: macro '{name}': {msg}")
        if not re.fullmatch(r"[A-Za-z]+", name):
            fail("macro name must contain letters only")
        if not isinstance(spec, dict):
            fail("entry must be a mapping with keys file, key, fmt, unit")
        for k in ("file", "key", "fmt"):
            if k not in spec:
                fail(f"missing field '{k}'")
        f = Path(derived_dir) / spec["file"]
        if f not in cache:
            if not f.is_file():
                fail(f"file not found: {f}")
            try:
                cache[f] = json.loads(f.read_text())
            except json.JSONDecodeError as e:
                fail(f"{f}: invalid JSON ({e})")
        try:
            val = lookup(cache[f], str(spec["key"]))
        except KeyError:
            fail(f"key path '{spec['key']}' not found in {f}")
        try:
            if spec["fmt"] == "sci":
                text = sci(val, spec.get("digits", 2))
            elif spec["fmt"] == "p":
                text = pfmt(val, spec.get("digits", 2))
            elif spec["fmt"] in ("sig", "floor"):
                text = sigfmt(val, spec.get("digits", 2), floor=spec["fmt"] == "floor")
            else:
                if "digits" in spec:
                    fail("'digits' applies only to fmt: sci, p, sig, floor")
                text = spec["fmt"].format(val)
                if "," in spec["fmt"]:  # thousands separator as a thin space, e.g. 20\,000
                    text = text.replace(",", "\\,")
        except (ValueError, TypeError, IndexError, KeyError) as e:
            fail(f"format '{spec['fmt']}' does not fit value {val!r} ({e})")
        src = f"{spec['file']}:{spec['key']}"
        lines.append(f"% {name} <- {src}")
        lines.append(f"\\newcommand{{\\{name}}}{{{text}}}")
        if spec["fmt"] == "p":
            lines.append(f"% {name}Rel <- relation and value of {src}")
            lines.append(f"\\newcommand{{\\{name}Rel}}{{{prel(val, spec.get('digits', 2))}}}")
        unit = spec.get("unit")
        if unit:
            lines.append(f"% {name}Unit <- unit of {src}")
            lines.append(f"\\newcommand{{\\{name}Unit}}{{{unit}}}")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--registry", default=ROOT / "paper" / "registry")
    ap.add_argument("--derived", default=ROOT / "data" / "derived")
    ap.add_argument("--out", default=ROOT / "paper" / "numbers.tex")
    a = ap.parse_args()
    text = build(a.registry, a.derived)
    Path(a.out).write_text(text)
    print(f"wrote {a.out} ({text.count('newcommand')} macros)")


if __name__ == "__main__":
    sys.exit(main())
