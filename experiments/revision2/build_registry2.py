"""Assemble paper/registry/revision2.yaml from the per-item registry files notes/C2_items/*.yaml
(A1 ... A12, B1, B2, in item order; items named on the command line are left out), checking that no macro is
defined twice here or in another registry file, then validate with tools/make_numbers.py.
Usage: build_registry2.py [ITEM ...]   (items to leave out)
"""
import os
import re
import subprocess
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(ROOT, "notes", "C2_items")
REG = os.path.join(ROOT, "paper", "registry")
OUT = os.path.join(REG, "revision2.yaml")


def key(f):
    m = re.match(r"([AB])(\d+)", f)
    return (m.group(1), int(m.group(2)), f) if m else ("Z", 0, f)


def main():
    skip = set(sys.argv[1:])
    others = {}
    for f in os.listdir(REG):
        if f.endswith(".yaml") and f != "revision2.yaml":
            for k in (yaml.safe_load(open(os.path.join(REG, f))) or {}):
                others[k] = f
    files = sorted((f for f in os.listdir(SRC) if f.endswith(".yaml") and f[:-5] not in skip), key=key)
    seen, parts = {}, ["# Registry entries for the revision-3 evidence (session C2). Generated by",
                       "# experiments/revision2/build_registry2.py from notes/C2_items/*.yaml; edit those.",
                       "# Sources: data/derived/rev2_*.json (experiments/revision2/*.py)."]
    for f in files:
        txt = open(os.path.join(SRC, f)).read()
        for k in (yaml.safe_load(txt) or {}):
            if k in seen or k in others:
                sys.exit(f"duplicate macro {k} in {f} and {seen.get(k) or others[k]}")
            seen[k] = f
        parts += ["", f"# ---- {f[:-5]}", txt.strip()]
    open(OUT, "w").write("\n".join(parts) + "\n")
    print(f"wrote {OUT}: {len(seen)} macros from {len(files)} files")
    subprocess.check_call([os.path.join(ROOT, ".venv", "bin", "python"), os.path.join(ROOT, "tools", "make_numbers.py")], cwd=ROOT)


if __name__ == "__main__":
    main()
