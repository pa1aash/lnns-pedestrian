"""Assemble notes/C3_items/revision4.yaml from notes/C3_items/T*.yaml (in item order), checking that no macro is
defined twice here or in paper/registry/*.yaml, then validate it with tools/make_numbers.py on a scratch copy of the
registry (paper/registry/*.yaml plus revision4.yaml) writing a scratch numbers.tex; paper/ is not written.
The paper session copies notes/C3_items/revision4.yaml to paper/registry/revision4.yaml.
Usage: build_registry4.py [SCRATCH_DIR]
"""
import os
import shutil
import subprocess
import sys
import tempfile

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(ROOT, "notes", "C3_items")
REG = os.path.join(ROOT, "paper", "registry")
OUT = os.path.join(SRC, "revision4.yaml")


def main():
    others = {}
    for f in os.listdir(REG):
        if f.endswith(".yaml") and f != "revision4.yaml":
            for k in (yaml.safe_load(open(os.path.join(REG, f))) or {}):
                others[k] = f
    files = sorted(f for f in os.listdir(SRC) if f.startswith("T") and f.endswith(".yaml"))
    seen, parts = {}, ["# Registry entries for the revision-4 evidence (session C3). Generated by",
                       "# experiments/revision4/build_registry4.py from notes/C3_items/T*.yaml; edit those.",
                       "# Sources: data/derived/rev4_*.json (experiments/revision4/*.py)."]
    for f in files:
        txt = open(os.path.join(SRC, f)).read()
        for k in (yaml.safe_load(txt) or {}):
            if k in seen or k in others:
                sys.exit(f"duplicate macro {k} in {f} and {seen.get(k) or others[k]}")
            seen[k] = f
        parts += ["", f"# ---- {f[:-5]}", txt.strip()]
    open(OUT, "w").write("\n".join(parts) + "\n")
    print(f"wrote {OUT}: {len(seen)} macros from {len(files)} files")
    tmp = sys.argv[1] if len(sys.argv) > 1 else tempfile.mkdtemp()
    reg = os.path.join(tmp, "registry")
    os.makedirs(reg, exist_ok=True)
    for f in os.listdir(REG):
        if f.endswith(".yaml"):
            shutil.copy(os.path.join(REG, f), reg)
    shutil.copy(OUT, os.path.join(reg, "revision4.yaml"))
    py = os.path.join(ROOT, ".venv", "bin", "python")
    subprocess.check_call([py, os.path.join(ROOT, "tools", "make_numbers.py"), "--registry", reg,
                           "--out", os.path.join(tmp, "numbers.tex")], cwd=ROOT)
    new = [l for l in open(os.path.join(tmp, "numbers.tex")) if l.startswith("\\newcommand{\\Rw")]
    open(os.path.join(SRC, "revision4_numbers.tex"), "w").writelines(new)
    print(f"{len(new)} Rw macro lines -> notes/C3_items/revision4_numbers.tex")


if __name__ == "__main__":
    main()
