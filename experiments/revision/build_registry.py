"""Assemble paper/registry/revision.yaml from the per-item registry files experiments/revision/notes/*.yaml
(A1 ... A15, B1 ... B6, in item order; items named on the command line are left out),
checking that no macro is defined twice, then validate with
tools/make_numbers.py. Usage: build_registry.py [ITEM ...]   (items to leave out, e.g. A2)
"""
import os
import re
import subprocess
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "paper", "registry", "revision.yaml")


def key(f):
    m = re.match(r"([AB])(\d+)", f)
    return (m.group(1), int(m.group(2))) if m else ("Z", 0)


def main():
    skip = set(sys.argv[1:])
    files = sorted((f for f in os.listdir(os.path.join(HERE, "notes")) if f.endswith(".yaml") and f[:-5] not in skip), key=key)
    seen, parts = {}, ["# Registry entries for the revision evidence (session C). Generated by",
                       "# experiments/revision/build_registry.py from experiments/revision/notes/*.yaml; edit those.",
                       "# Sources: data/derived/rev_*.json (experiments/revision/*.py)."]
    for f in files:
        txt = open(os.path.join(HERE, "notes", f)).read()
        d = yaml.safe_load(txt) or {}
        for k in d:
            if k in seen:
                sys.exit(f"duplicate macro {k} in {f} and {seen[k]}")
            seen[k] = f
        parts += ["", f"# ---- {f[:-5]}", txt.strip()]
    open(OUT, "w").write("\n".join(parts) + "\n")
    print(f"wrote {OUT}: {len(seen)} macros from {len(files)} files")
    subprocess.check_call([os.path.join(ROOT, ".venv", "bin", "python"), os.path.join(ROOT, "tools", "make_numbers.py")], cwd=ROOT)


if __name__ == "__main__":
    main()
