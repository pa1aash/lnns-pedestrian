"""Assemble notes/C4_items/revision5.yaml from notes/C4_items/X*.yaml (in item order), checking that no macro is
defined twice here, in paper/registry/*.yaml or in notes/C3_items/revision4.yaml (Rw, not yet copied into the paper), then validate it with tools/make_numbers.py on a scratch copy of the
registry (paper/registry/*.yaml plus revision4.yaml and revision5.yaml) writing a scratch numbers.tex; paper/ is not written.
The paper session copies notes/C4_items/revision5.yaml to paper/registry/revision5.yaml.
Usage: build_registry5.py [SCRATCH_DIR]
"""
import os
import shutil
import subprocess
import sys
import tempfile

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(ROOT, "notes", "C4_items")
RW = os.path.join(ROOT, "notes", "C3_items", "revision4.yaml")
REG = os.path.join(ROOT, "paper", "registry")
OUT = os.path.join(SRC, "revision5.yaml")


def main():
    others = {}
    for f in os.listdir(REG):
        if f.endswith(".yaml") and f != "revision5.yaml":
            for k in (yaml.safe_load(open(os.path.join(REG, f))) or {}):
                others[k] = f
    if os.path.exists(RW):
        for k in (yaml.safe_load(open(RW)) or {}):
            others.setdefault(k, "notes/C3_items/revision4.yaml")
    files = sorted(f for f in os.listdir(SRC) if f.startswith("X") and f.endswith(".yaml"))
    seen, parts = {}, ["# Registry entries for the revision-5 evidence (session C4). Generated by",
                       "# experiments/revision5/build_registry5.py from notes/C4_items/X*.yaml; edit those.",
                       "# Sources: data/derived/rev5_*.json (experiments/revision5/*.py)."]
    for f in files:
        txt = open(os.path.join(SRC, f)).read()
        for k in (yaml.safe_load(txt) or {}):
            if k in seen or k in others:
                sys.exit(f"duplicate macro {k} in {f} and {seen.get(k) or others[k]}")
            seen[k] = f
        parts += ["", f"# ---- {f[:-5]}", txt.strip()]
    open(OUT, "w").write("\n".join(parts) + "\n")
    print(f"wrote {OUT}: {len(seen)} macros from {len(files)} files")
    tmp = sys.argv[1] if len(sys.argv) > 1 else tempfile.mkdtemp()
    reg = os.path.join(tmp, "registry")
    os.makedirs(reg, exist_ok=True)
    for f in os.listdir(REG):
        if f.endswith(".yaml"):
            shutil.copy(os.path.join(REG, f), reg)
    if os.path.exists(RW) and not os.path.exists(os.path.join(reg, "revision4.yaml")):
        shutil.copy(RW, os.path.join(reg, "revision4.yaml"))
    shutil.copy(OUT, os.path.join(reg, "revision5.yaml"))
    py = os.path.join(ROOT, ".venv", "bin", "python")
    subprocess.check_call([py, os.path.join(ROOT, "tools", "make_numbers.py"), "--registry", reg,
                           "--out", os.path.join(tmp, "numbers.tex")], cwd=ROOT)
    new = [l for l in open(os.path.join(tmp, "numbers.tex")) if l.startswith("\\newcommand{\\Rx")]
    open(os.path.join(SRC, "revision5_numbers.tex"), "w").writelines(new)
    print(f"{len(new)} Rx macro lines -> notes/C4_items/revision5_numbers.tex")


if __name__ == "__main__":
    main()
